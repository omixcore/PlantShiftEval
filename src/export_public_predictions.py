"""Publish safe NumPy prediction arrays and run records without model binaries."""
import argparse,json,shutil
from pathlib import Path
import numpy as np
import torch
from run_corrected_study import matrix,valid_completed
from run_provenance import file_digest

def main():
    p=argparse.ArgumentParser();p.add_argument('--source-root',type=Path,required=True);p.add_argument('--repo',type=Path,default=Path(__file__).resolve().parents[1]);a=p.parse_args()
    out=a.repo/'evidence/corrected';out.mkdir(parents=True,exist_ok=True);index=[]
    for job in matrix():
        run=a.source_root/'runs_corrected'/job['run_id'];evaluation=a.source_root/'report/corrected'/job['run_id'];ep=evaluation/'evaluation.json'
        if not valid_completed(run) or not ep.exists():continue
        # These pickle-based .pt inputs were generated by the pinned study code
        # and verified against the completed run manifest, never arbitrary imports.
        b=torch.load(run/'logits.pt',map_location='cpu',weights_only=False)
        arrays={'source_logits':np.asarray(b['logits']),'source_labels':np.asarray(b['labels'])}
        for method,file in [('source_validation','source_validation.npz'),('target_zero_shot','target_zero_shot.npz'),('target_adabn','target_adabn.npz'),('target_supervised_ft','target_supervised_ft.npz')]:
            f=evaluation/file
            if not f.exists():continue
            with np.load(f,allow_pickle=False) as record:
                arrays[method+'_logits']=record['logits'];arrays[method+'_labels']=record['labels']
        dest=out/job['run_id'];dest.mkdir(exist_ok=True)
        prediction=dest/'predictions.npz'
        if prediction.exists():
            with np.load(prediction,allow_pickle=False) as existing:
                if set(existing.files)!=set(arrays) or any(not np.array_equal(existing[k],v) for k,v in arrays.items()):
                    raise ValueError('Existing public predictions differ from verified run outputs: '+job['run_id'])
        else:np.savez_compressed(prediction,**arrays)
        for name in ('metrics.json','run_manifest.json'):shutil.copyfile(run/name,dest/name)
        shutil.copyfile(ep,dest/'evaluation.json')
        index.append(dict(job,predictions_sha256=file_digest(prediction),arrays=list(arrays),
            source_checkpoint_sha256=file_digest(run/'model.pt')))
    (out/'index.json').write_text(json.dumps(index,indent=2)+'\n')
    print('Exported public prediction/run records:',len(index))

if __name__=='__main__':main()
